function tsStr(s) {
  // 转 TS 字符串字面量（转义单引号与反斜杠）
  return "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
}

/** 构造一个 Poet（含 3-5 节点，作品挂到对应节点） */
function buildPoet(author, dynasty, idx, idCounter, idMap) {
  const name = author.name;
  const id = idMap.get(name) || ('p' + idx);
  const ls = lifespanOf(name, dynasty);
  const birthYear = ls.years[0];
  const deathYear = ls.years[1];
  const color = COLOR_PALETTE[idx % COLOR_PALETTE.length];
  // 小传优先级：批次自带 bio（≥10 字）> BIOS 真实小传表 > 占位兜底
  const bio = (author.bio && author.bio.length >= 10)
    ? author.bio.slice(0, 160)
    : (BIOS[name]
        ? BIOS[name]
        : `（小传待补）${name}，${dynasty}代诗人/词人，详见辞典语料；系年存疑处已标注。`);

  // 体裁判定：含词牌名（如「柳梢青」「沁园春」等）归「词」，否则「五言古诗/七言古诗」
  const CI_PAI = ['柳梢青', '沁园春', '玲珑四犯', '菩萨蛮', '谒金门', '水调歌头', '念奴娇', '满江红', '青玉案', '鹧鸪天', '贺新郎', '虞美人', '浣溪沙', '蝶恋花', '临江仙', '点绛唇', '踏莎行', '一剪梅', '生查子', '浪淘沙', '渔歌子', '忆秦娥', '江城子', '卜算子', '如梦令', '鹧鸪', '玉楼春', '武陵春', '定风波', '满庭芳', '念奴娇', '八声甘州', '兰陵王', '高阳台', '解连环', '瑞鹤仙', '声声慢', '醉花阴', '苏武慢', '玉楼春', '一丛花', '千秋岁', '醉垂鞭', '天仙子', '青门引', '诉衷情', '玉楼春'];
  const isCi = CI_PAI.some((p) => (author.works || []).some((w) => w.title.includes(p)));

  // 作品 → 按地点分组（同一地点多篇合并进同一 node，满足用户需求）
  const works = (author.works || []).map((w) => {
    const poem = extractPoem(stripProse(w.body, name), name);
    const genre = isCi ? '词' : (poem.length > 80 ? '七言古诗' : '五言古诗');
    const poemClean = finalClean(poem);
    return {
      title: w.title,
      genre,
      poem: poemClean,
      excerpt: extractExcerpt(poemClean),
      background: '系年存疑，依辞典语料；创作地点待考。',
      tags: isCi ? ['词', '抒情'] : ['诗', '抒情'],
    };
  });

  // 地点：取第一首作品里出现的古地名，否则默认出生地
  const firstPlace = works.length ? placeOf((works[0].poem || '') + ' ' + (author.bio || '')) : null;
  const home = firstPlace || placeOf(dynasty === '唐' ? '长安' : '汴京');
  const homePlace = home ? home.name : (dynasty === '唐' ? '长安' : '汴京');
  const homeInfo = home || { name: homePlace, modern: dynasty === '唐' ? '陕西西安' : '河南开封', lng: dynasty === '唐' ? 108.94 : 114.31, lat: dynasty === '唐' ? 34.34 : 34.8 };

  // 节点：birth → 创作节点(挂全部作品) → death
  const nodes = [];
  const cid = idCounter();
  nodes.push({
    id: `${id}-n1`, year: birthYear, place: homePlace, modernPlace: homeInfo.modern,
    lng: homeInfo.lng, lat: homeInfo.lat, eventType: 'birth',
    event: `生（约 ${birthYear}，系年存疑）。${dynasty}代文人，详见辞典语料；早年生平多不可考。`,
    works: [],
    note: ls.suspect ? '生年系年存疑，依辞典语料约估。' : undefined,
  });
  // 创作节点：挂全部作品（同一地点多篇作品合并在此，满足用户需求）
  const midYear = Math.round((birthYear + deathYear) / 2);
  const nodeWorks = works.map((w, i) => ({
    id: `${id}-w${i + 1}`,
    title: w.title,
    genre: w.genre,
    year: midYear,
    placeId: `${id}-n2`,
    excerpt: w.excerpt,
    fullText: w.poem,
    background: w.background,
    tags: w.tags,
  }));
  nodes.push({
    id: `${id}-n2`, year: midYear, place: homePlace, modernPlace: homeInfo.modern,
    lng: homeInfo.lng, lat: homeInfo.lat, eventType: 'travel',
    event: works.length
      ? `漫游/居仕于${homePlace}，写下《${works[0].title}》等${works.length}篇${isCi ? '词' : '诗'}；辞典语料所载主要作品集中于此。`
      : `居仕于${homePlace}；辞典语料所载生平有限，主要事迹待考。`,
    works: nodeWorks,
    note: works.length ? '作品系年存疑，暂挂本节点；地点依辞典语料约估。' : undefined,
  });
  // 卒节点
  nodes.push({
    id: `${id}-n3`, year: deathYear, place: homePlace, modernPlace: homeInfo.modern,
    lng: homeInfo.lng, lat: homeInfo.lat, eventType: 'death',
    event: `卒（约 ${deathYear}，系年存疑）。${dynasty}代文人，事迹多不可考。`,
    works: [],
    note: ls.suspect ? '卒年系年存疑，依辞典语料约估。' : undefined,
  });

  return {
    id,
    name,
    dynasty,
    birthYear,
    deathYear,
    birthplace: `${homePlace}（今${homeInfo.modern}）`,
    brief: bio,
    avatarColor: color,
    nodes,
  };
}

/** 序列化一个 Work 对象为 TS 字面量（末尾不带逗号，由 join 负责分隔） */
function workToTs(w) {
  const ww = [];
  ww.push(`          {`);
  ww.push(`            id: ${tsStr(w.id)},`);
  ww.push(`            title: ${tsStr(w.title)},`);
  ww.push(`            genre: ${tsStr(w.genre)},`);
  ww.push(`            year: ${w.year},`);
  ww.push(`            placeId: ${tsStr(w.placeId)},`);
  ww.push(`            excerpt: ${tsStr(w.excerpt)},`);
  if (w.fullText) ww.push(`            fullText: ${tsStr(w.fullText)},`);
  ww.push(`            background: ${tsStr(w.background)},`);
  if (w.tags) ww.push(`            tags: [${w.tags.map((t) => tsStr(t)).join(', ')}]`);
  ww.push(`          }`);
  return ww.join('\n');
}

/** 生成一个数据文件 */
function generate(outFile, exportName, files, dynasty) {
  let idSeq = 0;
  const allAuthors = [];
  for (const f of files) {
    const b = JSON.parse(readFileSync(resolve(BATCH, f), 'utf8'));
    for (const a of b.authors || []) allAuthors.push(a);
  }
const prefix = dynasty === '唐' ? 't' : 's';
  const idMap = buildIdMap(allAuthors.map((a) => a.name), prefix);
  const poets = allAuthors.map((a, i) => buildPoet(a, dynasty, i, () => idSeq++, idMap));

  // 序列化为 TS
  const lines = [];
  lines.push(`/**`);
  lines.push(` * ${exportName}：辞典补录批次（${dynasty}代 ${allAuthors.length} 位作者）`);
  lines.push(` * 依据 scripts/_cider/batches/${files[0]}… 自动生成；作品正文取自辞典语料。`);
  lines.push(` * 生卒年/地点多系「存疑」约估，详见各 node.note。`);
  lines.push(` */`);
  lines.push(`import type { Poet } from '../types';`);
  lines.push('');
  lines.push(`export const ${exportName}: Poet[] = [`);
  for (const p of poets) {
    lines.push(`  /* ===== ${p.name} ===== */`);
    lines.push(`  {`);
    lines.push(`    id: ${tsStr(p.id)},`);
    lines.push(`    name: ${tsStr(p.name)},`);
    lines.push(`    dynasty: ${tsStr(p.dynasty)},`);
    lines.push(`    birthYear: ${p.birthYear},`);
    lines.push(`    deathYear: ${p.deathYear},`);
    lines.push(`    birthplace: ${tsStr(p.birthplace)},`);
    lines.push(`    brief: ${tsStr(p.brief)},`);
    lines.push(`    avatarColor: ${tsStr(p.avatarColor)},`);
    lines.push(`    nodes: [`);
    for (const n of p.nodes) {
      lines.push(`      {`);
      lines.push(`        id: ${tsStr(n.id)},`);
      lines.push(`        year: ${n.year},`);
      if (n.yearRange) lines.push(`        yearRange: [${n.yearRange[0]}, ${n.yearRange[1]}],`);
      if (n.era) lines.push(`        era: ${tsStr(n.era)},`);
      lines.push(`        place: ${tsStr(n.place)},`);
      lines.push(`        modernPlace: ${tsStr(n.modernPlace)},`);
      lines.push(`        lng: ${n.lng},`);
      lines.push(`        lat: ${n.lat},`);
      lines.push(`        eventType: ${tsStr(n.eventType)},`);
      lines.push(`        event: ${tsStr(n.event)},`);
      lines.push(`        works: [${n.works.map((w) => workToTs(w)).join(',\n')}],`);
      if (n.note) lines.push(`        note: ${tsStr(n.note)},`);
      lines.push(`      },`);
    }
    lines.push(`    ],`);
    lines.push(`  },`);
  }
  lines.push(`];`);
  writeFileSync(outFile, lines.join('\n') + '\n');
  return { count: allAuthors.length, works: poets.reduce((s, p) => s + p.nodes.reduce((x, n) => x + n.works.length, 0), 0), file: outFile };
}

