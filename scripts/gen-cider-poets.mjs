/** 预处理：在 extractPoem 之前，先把 body 里夹在正文后的赏析散文整段切掉。
 *  判据：赏析段以「这是一/这首/此词/这是一首/历来/素来/小序/本事/…写/…诗/…词」开头，
 *  且其后是 30+ 字散文。取最早出现的赏析起点，截断到该点之前。 */
function stripProse(body, authorName) {
  let t = (body || '').trim();
  t = t.replace(/〔注〕[\s\S]*$/, '');
  t = t.replace(/\[\d+\]/g, '');
  t = t.replace(/〔[^〕]*〕/g, '');
  t = t.replace(new RegExp(`^${authorName}\\s*`), '');
  t = t.replace(/[ \t]+/g, ' ').trim();
  // 全面赏析特征词（散文叙述/评论；韵文短句不含）
  const KW = ['这首','此词','此诗','是一首','这是一','是一篇','小序','本事','女主人公','词人','诗人','名臣','悼亡','恋情','怀古','忠愤','感时','应制','夜行','春闺','闺情','送客','客中','七言古诗','七言绝句','乐府','拟古','讽','写景','抒情','小词','小令','词作','诗作','歌行体','民歌','即事抒怀','题画','赞美','闲适','情味','淡雅','清丽','蕴藉','婉转','深曲','摇曳','多姿','写得很','很有','无可取','歌功颂德','粉饰太平','寄居','草堂','落第','应举','长安东','电影','镜头','客观','主观','上片','下片','歇拍','过片','领字','点题','用典','化用','咏物诗','咏物','这是一首','这是首'];
  const sents = t.split(/(?<=[。！？])/).map((s) => s.trim()).filter(Boolean);
  const kept = [];
  for (const s of sents) {
    const hit = KW.some((k) => s.includes(k));
    const len = s.length;
    // 赏析句：含特征词 且 长度 > 4 字（短赏析标签如"这是一首闲适诗。"也要截断）
    if (hit && len > 4) break;
    // 无特征词但 >40 字的超长散文也截断
    if (len > 40) break;
    kept.push(s.replace(/[。！？]$/, ''));
  }
  return kept.join('。') + (kept.length ? '。' : '');
}

/** 取作品正文：裁掉赏析尾文、〔注〕、角标，保留诗/词原文。
 *  原理：诗/词正文由 5-9 字短句（韵文节奏）构成；赏析是 30+ 字散文长句。
 *  按「。，」切句，保留短句、丢弃首个散文长句之后的全部内容。
 *  散文判定：该句 >14 字，或含赏析特征词（词人/诗人/这首/此词/上片/下片/名臣/典故等）。 */
function extractPoem(body, authorName) {
  let t = (body || '').trim();
  // 去 〔注〕… 到末尾
  t = t.replace(/〔注〕[\s\S]*$/, '');
  // 去行内角标 [1][2]
  t = t.replace(/\[\d+\]/g, '');
  // 去 〔…〕
  t = t.replace(/〔[^〕]*〕/g, '');
  // 去开头作者名
  t = t.replace(new RegExp(`^${authorName}\\s*`), '');
  // 压缩空白
  t = t.replace(/[ \t]+/g, ' ').trim();
  // 按「。，」切句（保留句号在句尾），保留短句、遇到散文长句即截断
  const PROSE_RE = /词人|诗人|这首|此词|此诗|全诗|全词|上片|下片|名臣|典故|起句|首句|结尾|歇拍|过片|领字|点题|用典|化用|借用|写于|作于|是宋代|是唐代|南渡|北伐|靖康|建炎|绍兴|词前|词后|这首小词|这首词|一首词|一首诗|这首小令|此词作|此诗作|词牌|词意|诗意|词中|诗中|词作|诗作|这首绝句|这首律诗|这首古体|这首乐府|这首小词|这首词|这首小令|素来|素|乃是|一位|慵倦|孤独|寂寞|女子|女主人公|郎君|痴想|奇想|何能|有何|时间推移|过程|历来|咏|的开|为封建|统治者|减轻|罪责|落第|寄居|草堂|应举|长安东|大约写|写作|所作|所作诗|此诗是|此词是|这首是/;
  const sents = t.split(/(?<=[。！？])/).map((s) => s.trim()).filter(Boolean);
  const kept = [];
  for (const s of sents) {
    // 散文句：>14 字 且（无逗号分隔的短句节奏 或 含赏析特征词）
    const shortRhythm = s.length <= 14;
    const hasProseWord = PROSE_RE.test(s);
    if (!shortRhythm && hasProseWord) break; // 散文长句
    // 超长句（>40 字）无论是否有特征词，大概率是赏析
    if (s.length > 40) break;
    kept.push(s.replace(/[。！？]$/, ''));
  }
  return kept.join('。') + '。';
}

/** 最终清洗：对 fullText 做最后一遍散文截断（兜底未清的赏析） */
function finalClean(poem) {
  if (!poem) return '';
  // 全面赏析特征词（散文叙述/评论性用语；韵文短句不含这些）
  const P = /这首|此词|此诗|全诗|全词|历来|素来|是一首|这是首|这是一|是一篇|是一首|小序|本事|女主人公|词人|诗人|名臣|悼亡|恋情|怀古|忠愤|感时|应制|夜行|春闺|闺情|送客|客中|议论|七言古诗|七言绝句|乐府|拟古|讽|刺诗|写景|抒情|小词|小令|词作|诗作|歌行体|民歌|即事抒怀|题画|赞美|闲适|情味|淡雅|清丽|蕴藉|婉转|深曲|摇曳|多姿|写得很|很有|无可取|歌功颂德|粉饰太平|寄居|草堂|落第|应举|长安东|电影|镜头|客观|主观|慵倦|孤独|寂寞|痴想|奇想|如何|何能|时间推移|的开|为封建|统治者|罪责|寄赠|是臣下|这类|上下片|上片|下片|歇拍|过片|领字|点题|用典|化用|寄居|草堂/;
  const sents = poem.split(/(?<=[。！？])/).map((s) => s.trim()).filter(Boolean);
  const kept = [];
  for (const s of sents) {
    const proseHit = P.test(s);
    // 散文句：含赏析特征词 且 是长句（>8 字）→ 截断
    if (proseHit && s.length > 8) break;
    // 无特征词但超长（>40 字）的散文句也截断
    if (s.length > 40) break;
    kept.push(s.replace(/[。！？]$/, ''));
  }
  return kept.join('。') + (kept.length ? '。' : '');
}

/** 提取名句 excerpt：取正文前 1-4 句（按句号/逗号切） */
function extractExcerpt(poem, max = 4) {
  const parts = poem.split(/(?<=[。！？])/).filter(Boolean);
  return parts.slice(0, max).join('');
}

/**
 * id 生成策略（彻底修掉拼音简化解码冲突）：
 * - 全名按「拼音序」做**全局稳定排序**，取每位作者的 pinyin-rank 作为唯一编号；
 * - id = `t<pinyinRank>` / `s<pinyinRank>`（唐/宋各自编号，前缀区分朝代），
 *   例如 皇甫松→t1（拼音 huangfu… 最早）、李德裕→t201、司马光→s…；
 * - 全局 rank 保证 **绝不重复**、**重跑结果稳定**（确定性排序），彻底消除
 *   旧 toPinyin 只取姓氏导致的 li×21 / zhang×14 等 197 处 id 碰撞。
 * - 旧 PINYIN_MAP / toPinyin 保留仅作注释参考，不再使用。
 */
const PINYIN_MAP_DEPRECATED = {
  李: 'li', 贺: 'he', 贾: 'jia', 岛: 'dao', 群: 'qun', 玉: 'yu', 罗: 'luo',
};

/**
 * 构建「姓名 → 唯一 id」映射：
 * 1) 全体姓名按拼音序稳定排序（Node ICU zh-Hans-CN），rank 从 1 起；
 * 2) 同拼音序内按码位二次排序，保证 rank 100% 确定、重跑不变；
 * 3) id = `<prefix><rank>`（prefix = 't' 唐 / 's' 宋）。
 * 返回 name→id 的 Map，调用方按姓名取。
 */
function buildIdMap(allNames, prefix) {
  const names = [...new Set(allNames)];
  names.sort((a, b) => {
    const c = a.localeCompare(b, 'zh-Hans-CN', { numeric: true });
    if (c !== 0) return c;
    // 同音/同序按码位稳定排序
    for (let i = 0; i < Math.min(a.length, b.length); i++) {
      const ca = a.codePointAt(i), cb = b.codePointAt(i);
      if (ca !== cb) return ca - cb;
    }
    return a.length - b.length;
  });
  const map = new Map();
  names.forEach((name, i) => map.set(name, `${prefix}${i + 1}`));
  return map;
}

